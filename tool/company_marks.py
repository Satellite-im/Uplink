#!/usr/bin/env python3
"""The marks of the companies that send sign-in codes, for the Codes section's faces (lib/plugins/companies.dart).

Matt, 2026-11-14, asked where the logos should come from: "download in the app look for brand icon packs that
might exist". The pack is Simple Icons (simpleicons.org; CC0 1.0), as Iconify packages it: one file of every
mark, each a single path on a 24 by 24 square.

    npm pack @iconify-json/simple-icons        # in a folder of its own; then: tar -xzf the .tgz
    python3 tool/company_marks.py <that folder>/package

It reads the companies from lib/plugins/companies.dart, finds each one's mark by its name (or by SLUGS below where
the pack calls it something else), and writes lib/plugins/company_marks.g.dart, keyed by the company's web address.

A company the pack does not have (most banks and shops) gets a letter in its colour instead.

Some marks the pack has taken out and keeps only so older uses do not break ("hidden": Amazon, Microsoft, LinkedIn
and others); Simple Icons takes one out when its owner asks or its owner's rules do not allow such use. They were
first left out here too. Matt, told of them and asked whether to keep letters for those companies: "Use older
logos". So they are taken (OLDER below), as the pack last had them, and the file this writes says which they are.

The pack is read as data: nothing in it is run. The marks are trademarks of their owners, drawn only to say who a
text is from.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPANIES = os.path.join(ROOT, 'lib', 'plugins', 'companies.dart')
OUT = os.path.join(ROOT, 'lib', 'plugins', 'company_marks.g.dart')
# The networks Settings › Me links (lib/me/me.dart), whose rows wear their own logos (Matt, 2026-11-14: "use the
# real brandicons on the icons for discord telegram and X and bluesky and github etc"). `--networks` writes these
# alone, leaving the companies' file as it is.
NETWORKS = os.path.join(ROOT, 'lib', 'me', 'me.dart')
NETWORKS_OUT = os.path.join(ROOT, 'lib', 'me', 'network_marks.g.dart')
# The services a link card names (lib/plugins/embeds.dart; Matt, 2026-11-14: "smart embeds added to expand spotify
# links, youtube, etc"), by the id embeds.dart gives each, with its colour. `--embeds` writes these alone.
EMBEDS = [
    ('youtube', 'youtube'), ('youtubemusic', 'youtubemusic'), ('spotify', 'spotify'), ('applemusic', 'applemusic'),
    ('applepodcasts', 'applepodcasts'), ('soundcloud', 'soundcloud'), ('vimeo', 'vimeo'), ('tiktok', 'tiktok'),
    ('x', 'x'), ('reddit', 'reddit'), ('instagram', 'instagram'), ('twitch', 'twitch'), ('bandcamp', 'bandcamp'),
    ('pinterest', 'pinterest'),
]
EMBEDS_OUT = os.path.join(ROOT, 'lib', 'plugins', 'embed_marks.g.dart')

# Whether the marks the pack has taken out and still carries are used (Matt, 2026-11-14: "Use older logos").
OLDER = True

# Where the pack's name for a company is not its name run together in small letters.
SLUGS = {
    'booking.com': 'bookingdotcom',
}


# A name as the pack keys its icons: lower case, letters and digits only, "+" and "&" spelt out.
def slug_of(name):
    return re.sub(r'[^a-z0-9]', '', name.lower().replace('+', 'plus').replace('&', 'and'))


def single_path(icon):
    """The one filled path a mark is, or None where it is anything else."""
    m = re.fullmatch(r'<path fill="currentColor" d="([^"]+)"/>', icon['body'])
    if not m or not re.fullmatch(r'[MmLlHhVvCcSsQqTtAaZz0-9eE .,+-]+', m.group(1)):
        return None
    return m.group(1)


# --networks: writes the Dart map of the logos of the networks named in NETWORKS, by each network's id, and says
# which the pack does not have.
def networks(pack, info, icons):
    found, missing = [], []
    for nid, name in re.findall(r"Network\('([a-z]+)', '([^']+)'", open(NETWORKS).read()):
        icon = icons.get(slug_of(name))
        d = single_path(icon) if icon else None
        if d is None:
            missing.append(name)
        else:
            found.append((nid, name, d))
    lines = [
        '// GENERATED by tool/company_marks.py --networks. Do not edit: run it again.',
        '//',
        '// The logos of the networks Settings › Me links (lib/me/me.dart), from %s %s (%s; simpleicons.org).' % (info['name'], info.get('version', ''), info['license']['title']),
        '// Each is one path on a 24 by 24 square, by the network\'s id. The marks are trademarks of their owners, drawn',
        '// only to say which network an account is on.',
        'library;',
        '',
        'const Map<String, String> networkMarks = {',
    ]
    for nid, name, d in found:
        lines.append("  // %s" % name)
        lines.append("  '%s': '%s'," % (nid, d))
    lines.append('};')
    open(NETWORKS_OUT, 'w').write('\n'.join(lines) + '\n')
    print('%d network logos written to %s; not in the pack: %s' % (len(found), os.path.relpath(NETWORKS_OUT, ROOT), ', '.join(missing) or 'none'))


# --embeds: writes the Dart map of the marks of the services a link card names (EMBEDS), by each service's id.
def embeds(pack, info, icons):
    lines = [
        '// GENERATED by tool/company_marks.py --embeds. Do not edit: run it again.',
        '//',
        '// The marks of the services a link card names (lib/plugins/embeds.dart), from %s %s (%s; simpleicons.org).' % (info['name'], info.get('version', ''), info['license']['title']),
        '// Each is one path on a 24 by 24 square, by the service\'s id. The marks are trademarks of their owners, drawn',
        '// only to say where a link goes.',
        'library;',
        '',
        'const Map<String, String> embedMarks = {',
    ]
    missing = []
    for eid, slug in EMBEDS:
        icon = icons.get(slug)
        d = single_path(icon) if icon else None
        if d is None:
            missing.append(eid)
            continue
        lines.append("  '%s': '%s'," % (eid, d))
    lines.append('};')
    open(EMBEDS_OUT, 'w').write('\n'.join(lines) + '\n')
    print('%d service marks written to %s; not in the pack: %s' % (len(EMBEDS) - len(missing), os.path.relpath(EMBEDS_OUT, ROOT), ', '.join(missing) or 'none'))


def main():
    args = [a for a in sys.argv[1:] if a not in ('--networks', '--embeds')]
    if len(args) != 1:
        sys.exit(__doc__)
    pack = args[0]
    info = json.load(open(os.path.join(pack, 'info.json')))
    data = json.load(open(os.path.join(pack, 'icons.json')))
    if info.get('license', {}).get('spdx') != 'CC0-1.0' or data.get('width', 24) != 24 or data.get('height', 24) != 24:
        sys.exit('Not the pack this was written for: its licence or its square is not as expected.')
    icons = data['icons']
    if '--networks' in sys.argv:
        return networks(pack, info, icons)
    if '--embeds' in sys.argv:
        return embeds(pack, info, icons)
    companies = re.findall(r"Company\('((?:[^'\\]|\\.)+)', '([^']+)'", open(COMPANIES).read())
    found, hidden, missing = [], [], []
    for name, domain in companies:
        slug = SLUGS.get(domain, slug_of(name))
        icon = icons.get(slug)
        if icon is None:
            missing.append(name)
            continue
        if icon.get('hidden'):
            hidden.append(name)
            if not OLDER:
                continue
        # One path, filled, and nothing else: what the app's own path reader draws.
        m = re.fullmatch(r'<path fill="currentColor" d="([^"]+)"/>', icon['body'])
        if not m or not re.fullmatch(r'[MmLlHhVvCcSsQqTtAaZz0-9eE .,+-]+', m.group(1)):
            missing.append(name + ' (not a single path)')
            continue
        found.append((domain, name, m.group(1)))
    lines = [
        '// GENERATED by tool/company_marks.py. Do not edit: run it again.',
        '//',
        '// The marks of the companies lib/plugins/companies.dart knows, from %s %s (%s; %s).' % (info['name'], info.get('version', ''), info['license']['title'], 'simpleicons.org'),
        '// Each is one path on a 24 by 24 square, by the company\'s web address. %d of %d companies have one; the rest' % (len(found), len(companies)),
        '// get a letter in their colour (the pack has no mark for them).',
        '// %d of these the pack has since taken out and still carries for older uses; they are here as it last had' % (len([h for h in hidden if OLDER])),
        '// them, at Matt\'s choice ("Use older logos"): %s.' % ', '.join(hidden),
        '// The marks are trademarks of their owners, drawn only to say who a text is from.',
        'library;',
        '',
        'const Map<String, String> companyMarks = {',
    ]
    for domain, name, d in sorted(found):
        lines.append("  // %s" % name)
        lines.append("  '%s': '%s'," % (domain, d))
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('%s %s: %d marks written to %s' % (info['name'], info.get('version', ''), len(found), os.path.relpath(OUT, ROOT)))
    print('taken out of the pack since, %s (%d): %s' % ('used as it last had them' if OLDER else 'left as letters', len(hidden), ', '.join(hidden)))
    print('not in the pack, left as letters (%d): %s' % (len(missing), ', '.join(missing)))


if __name__ == '__main__':
    main()
