// (<relay-routes group="…"/>) and the Postman collection from this one list. A route added to the relay is added here.
//   id       unique, lowercase-with-hyphens; the anchor on the page (e.g. 'files-blob-put')
//   method   GET | POST | PUT | DELETE | HEAD
//   path     from the server's root, parameters in braces: '/files/{space}/blobs/{blob}'
//   summary  one or two plain sentences: what it does
//   who      who may call it, in a few words ('Anyone', 'Holder of the space token', 'Signed: the developer', 'Review')
//   auth     'none' | 'files-token' | 'files-signed' | 'market-signed' | 'feedback-signed'  (which header set it needs)
//   params   [{ name, in: 'path'|'query'|'header'|'body', required: true|false, doc }]  (not the auth headers: those come from `auth`)
//   body     { type: 'none'|'json'|'binary', example?: <a real example object for json> }
//   answers  the success answer as a short shape: '200 {"ok": true, "plugins": [...]}'
//   errors   ['404 {"err": "gone"}', …] the refusals worth knowing, status first
// A route signed in a way of its own (POST /bounty) has auth 'none' and lists its three headers in params.

